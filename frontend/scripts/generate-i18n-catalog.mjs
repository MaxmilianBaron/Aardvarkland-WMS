import { mkdir, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { auditI18nSources } from './i18n-source-audit.mjs';

const languages = ['fr', 'de', 'es'];
const audit = await auditI18nSources();
const values = audit.englishValues
  .map((entry) => entry.value)
  .filter((value) => !value.startsWith('`'));
const translated = new Map(values.map((value) => [value, {}]));

for (const language of languages) {
  process.stdout.write(`Translating ${values.length} entries to ${language}...\n`);
  for (const batch of batches(values, 45)) {
    const parsed = await translateBatch(batch, language);
    batch.forEach((value, index) => {
      translated.get(value)[language] = parsed[index];
    });
  }
}

const rows = [...translated.entries()].map(([english, translations]) => (
  `  ${JSON.stringify(english)}: { fr: ${JSON.stringify(translations.fr)}, de: ${JSON.stringify(translations.de)}, es: ${JSON.stringify(translations.es)} },`
));
const output = `/* eslint-disable */\n// Generated from active frontend English copy by scripts/generate-i18n-catalog.mjs.\n// Review domain terminology before a customer release; do not edit this file manually.\nexport const generatedTranslations = {\n${rows.join('\n')}\n} as const;\n`;
const destination = fileURLToPath(new URL('../src/core/i18n/translations.generated.ts', import.meta.url));
await mkdir(dirname(destination), { recursive: true });
await writeFile(destination, output, 'utf8');
process.stdout.write(`Wrote ${translated.size} translation rows.\n`);

async function translateBatch(batch, targetLanguage) {
  if (batch.length === 1) return [await translate(batch[0], targetLanguage)];
  const payload = batch.map((value, index) => `[WMS${String(index).padStart(4, '0')}] ${value.replaceAll('\n', ' ')}`).join('\n');
  const output = await translate(payload, targetLanguage);
  try {
    return parseMarkedTranslations(output, batch.length);
  } catch {
    const middle = Math.ceil(batch.length / 2);
    return [
      ...await translateBatch(batch.slice(0, middle), targetLanguage),
      ...await translateBatch(batch.slice(middle), targetLanguage),
    ];
  }
}

async function translate(text, targetLanguage) {
  const url = new URL('https://translate.googleapis.com/translate_a/single');
  url.searchParams.set('client', 'gtx');
  url.searchParams.set('sl', 'en');
  url.searchParams.set('tl', targetLanguage);
  url.searchParams.set('dt', 't');
  url.searchParams.set('q', text);

  let lastError;
  for (let attempt = 1; attempt <= 4; attempt += 1) {
    try {
      const response = await fetch(url);
      if (!response.ok) throw new Error(`Translation request failed with HTTP ${response.status}.`);
      const body = await response.json();
      return body[0].map((part) => part[0]).join('');
    } catch (error) {
      lastError = error;
      await new Promise((resolve) => setTimeout(resolve, attempt * 350));
    }
  }
  throw lastError;
}

function parseMarkedTranslations(output, expectedCount) {
  const matches = [...output.matchAll(/\[WMS(\d{4})\]\s*([\s\S]*?)(?=\n\[WMS\d{4}\]|$)/g)];
  if (matches.length !== expectedCount) {
    throw new Error(`Translation response returned ${matches.length}/${expectedCount} marked rows.`);
  }
  const parsed = Array(expectedCount);
  for (const match of matches) parsed[Number(match[1])] = match[2].trim();
  if (parsed.some((value) => !value)) throw new Error('Translation response contained an empty row.');
  return parsed;
}

function batches(items, size) {
  const result = [];
  for (let index = 0; index < items.length; index += size) result.push(items.slice(index, index + size));
  return result;
}
